#!/usr/bin/env node
// Builds the landing page for the hosted demo. Reads the manifests that were just
// generated so the headline numbers are real rather than hardcoded.
import fs from "node:fs";
import path from "node:path";

const siteDir = process.argv[2] || "site";

const DEMOS = [
  { slug: "express", name: "expressjs/express", url: "https://github.com/expressjs/express" },
  { slug: "vue", name: "vuejs/core", url: "https://github.com/vuejs/core" },
  { slug: "axios", name: "axios/axios", url: "https://github.com/axios/axios" },
];

const cards = DEMOS.flatMap((demo) => {
  const manifestPath = path.join(siteDir, `${demo.slug}.cartograph.json`);
  if (!fs.existsSync(manifestPath)) {
    console.warn(`skipping ${demo.slug}: no manifest at ${manifestPath}`);
    return [];
  }
  const m = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
  const loc = m.nodes.reduce((sum, n) => sum + (n.loc || 0), 0);
  return [{ ...demo, files: m.nodes.length, edges: m.edges.length, clusters: m.clusters.length, loc }];
});

if (!cards.length) {
  console.error("No manifests found — refusing to publish an empty demo page.");
  process.exit(1);
}

const n = (v) => v.toLocaleString("en-US");

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Cartograph — live maps</title>
<style>
  :root {
    --ground:#0A2440; --panel:#153B57; --ink:#EAF1F6; --brass:#D6A85A;
    --rule:rgba(234,241,246,0.34); --rule-soft:rgba(234,241,246,0.12);
    --mono:ui-monospace,SFMono-Regular,"SF Mono",Menlo,Consolas,monospace;
    --sans:system-ui,-apple-system,"Segoe UI",sans-serif;
  }
  *{margin:0;padding:0;box-sizing:border-box}
  body{background:var(--ground);color:var(--ink);font-family:var(--sans);
       -webkit-font-smoothing:antialiased;min-height:100vh;
       background-image:linear-gradient(rgba(234,241,246,.05) 1px,transparent 1px),
                        linear-gradient(90deg,rgba(234,241,246,.05) 1px,transparent 1px);
       background-size:48px 48px}
  .wrap{max-width:940px;margin:0 auto;padding:72px 24px 96px}
  h1{font-size:13px;letter-spacing:7px;text-transform:uppercase;font-weight:600;color:var(--brass)}
  .lede{font-size:20px;line-height:1.5;margin-top:22px;max-width:640px}
  .sub{font-size:14.5px;line-height:1.6;margin-top:16px;max-width:640px;opacity:.72}
  .grid{display:grid;grid-template-columns:repeat(auto-fit,minmax(300px,1fr));gap:20px;margin-top:44px}
  .card{background:var(--panel);border:1px solid var(--rule);position:relative;
        text-decoration:none;color:inherit;display:block;transition:border-color .15s}
  .card:hover{border-color:var(--brass)}
  .card::before,.card::after{content:"";position:absolute;width:11px;height:11px}
  .card::before{top:6px;left:6px;border-top:1px solid var(--brass);border-left:1px solid var(--brass)}
  .card::after{bottom:6px;right:6px;border-bottom:1px solid var(--brass);border-right:1px solid var(--brass)}
  .card-head{padding:14px 18px;border-bottom:1px solid var(--rule);
             font-family:var(--mono);font-size:14px;color:var(--brass)}
  .stats{display:grid;grid-template-columns:1fr 1fr;gap:1px;background:rgba(234,241,246,.2)}
  .stat{background:var(--panel);padding:12px 18px}
  .stat .k{font-size:9.5px;letter-spacing:2.6px;text-transform:uppercase;opacity:.5}
  .stat .v{font-family:var(--mono);font-size:15px;margin-top:5px}
  .card-foot{padding:12px 18px;font-family:var(--mono);font-size:11px;
             letter-spacing:1.4px;text-transform:uppercase;color:var(--brass)}
  .links{margin-top:12px;padding:0 18px 14px;display:flex;gap:16px}
  .links a{font-family:var(--mono);font-size:11px;opacity:.55;color:inherit}
  .links a:hover{opacity:1;color:var(--brass)}
  footer{margin-top:56px;padding-top:24px;border-top:1px solid var(--rule-soft);
         font-size:13.5px;line-height:1.7;opacity:.7}
  footer a{color:var(--brass)}
  @media(max-width:600px){.wrap{padding:44px 18px 64px}.lede{font-size:17px}}
</style>
</head>
<body>
<div class="wrap">
  <h1>Cartograph</h1>
  <p class="lede">Every coding agent works out which files in your repo actually matter — privately, and from scratch every session. Cartograph is the persisted, readable record of that.</p>
  <p class="sub">These maps were generated by the scanner in CI, with no API key and no network calls. Node size is how much depends on a file; lines are imports; groups are subsystems found by community detection. Click a file to see what it holds up.</p>

  <div class="grid">
${cards
  .map(
    (c) => `    <a class="card" href="${c.slug}.html">
      <div class="card-head">${c.name}</div>
      <div class="stats">
        <div class="stat"><div class="k">Files</div><div class="v">${n(c.files)}</div></div>
        <div class="stat"><div class="k">Imports</div><div class="v">${n(c.edges)}</div></div>
        <div class="stat"><div class="k">Subsystems</div><div class="v">${n(c.clusters)}</div></div>
        <div class="stat"><div class="k">Lines</div><div class="v">${n(c.loc)}</div></div>
      </div>
      <div class="card-foot">Open the map &rarr;</div>
    </a>`,
  )
  .join("\n")}
  </div>

  <div class="links" style="padding:0;margin-top:20px">
${cards
  .map(
    (c) =>
      `    <a href="${c.slug}.AGENTS.md">${c.slug} AGENTS.md</a>\n    <a href="${c.slug}.cartograph.json">${c.slug} cartograph.json</a>`,
  )
  .join("\n")}
  </div>

  <footer>
    Clusters are numbered rather than named here: naming them is an opt-in LLM pass, and the demo builds without any credentials.
    <br><a href="https://github.com/AnshSingh30/cartograph">Source and docs on GitHub</a>
  </footer>
</div>
</body>
</html>
`;

fs.writeFileSync(path.join(siteDir, "index.html"), html);
console.log(`Wrote ${path.join(siteDir, "index.html")} with ${cards.length} demo(s).`);
